const cache = new Map<string, string>();
export function cardIcon(id: string, school: School): string {
  const key = id + school;
  const hit = cache.get(key);
  if (hit) return hit;
  const c = document.createElement('canvas');
  c.width = c.height = 12;
  const g = c.getContext('2d')!;
  g.fillStyle = '#1a1214';
  g.fillRect(0, 0, 12, 12);
  g.fillStyle = SCHOOL_COLOR[school];
  g.fillRect(0, 0, 12, 1); g.fillRect(0, 11, 12, 1); g.fillRect(0, 0, 1, 12); g.fillRect(11, 0, 1, 12);
  const rows = (GLYPHS[id] ?? '..####..|.#....#.|#..##..#|#.#..#.#|#..##..#|.#....#.|..####..|........').split('|');
  rows.forEach((r, y) => { for (let x = 0; x < r.length; x++) if (r[x] === '#') { g.fillStyle = '#f2e6c8'; g.fillRect(x + 2, y + 2, 1, 1); } });
  const url = c.toDataURL();
  cache.set(key, url);
  return url;
}
